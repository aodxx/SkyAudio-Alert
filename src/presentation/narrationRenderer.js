const { getFact } = require('./facts');
const { getExplainer } = require('./explainers/th');

const SEVERITY_LABELS = Object.freeze({
  normal: 'ปกติ',
  watch: 'เฝ้าระวัง',
  affected: 'ได้รับผลกระทบ',
  critical: 'วิกฤต',
  unknown: 'ยังยืนยันไม่ได้',
});

function factDisplay(fact) {
  if (!fact) return '';
  const value = fact.displayValue || fact.value;
  if (value === undefined || value === null || value === '') return '';
  return `${value}${fact.unit || ''}`.trim();
}

function factSentences(segment, snapshot) {
  return (segment.allowedFactIds || []).map((id) => {
    const fact = getFact(snapshot, id);
    const value = factDisplay(fact);
    if (!value) return '';
    if (id.endsWith('.name') || fact?.kind === 'name') return `ข้อมูลระบุชื่อว่า ${value}`;
    if (fact?.kind === 'time') return `เวลาที่เกี่ยวข้องกับข้อมูลนี้คือ ${value}`;
    return `${value}`;
  }).filter(Boolean);
}

function explainers(segment) {
  return (segment.explainerIds || []).map((id) => getExplainer(id)?.text || '').filter(Boolean);
}

function joinFacts(values) {
  if (!values.length) return 'รอบนี้ยังไม่มีค่ารายละเอียดจากแหล่งข้อมูลในหัวข้อนี้';
  if (values.length === 1) return values[0];
  return `${values.slice(0, -1).join(' , ')} และ ${values.at(-1)}`;
}

