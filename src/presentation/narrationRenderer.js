function renderNarrationPlan(plan, snapshot) {
  if (!plan || !Array.isArray(plan.segments)) throw new Error('NarrationPlan is required for rendering');
  const sections = plan.segments.map((segment, index) => ({
    id: segment.id,
    title: segment.purpose,
    text: renderSegment(segment, snapshot, index),
    factsUsed: [...segment.allowedFactIds],
  }));
  const spokenText = sections.map((section) => section.text).join('\n');
  return { sections, spokenText, totalCharacters: spokenText.length, provider: 'deterministic-narration-plan' };
}

module.exports = { renderNarrationPlan, renderSegment, factDisplay };
